"""Write code_ranges.tex: the line range of every code excerpt quoted in dwave_in_the_code.tex,
found in the CURRENT source by pattern, so the document never quotes stale line numbers.
Run by build.sh before pdflatex."""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / "unlearnable_games_explanation"
B, M, E, P, Q, S = ("skgame/optim/backends.py", "main_simulation.py", "skgame/optim/embedding.py",
                    "skgame/optim/problem.py", "skgame/optim/quantum.py", "skgame/optim/solvers.py")

# name: (file, start pattern, end) with end = None (end of the start's block),
# ("block", pattern) (end of the block of a later line), ("line", pattern, k) (k-th later line matching),
# ("before", pattern) (the line before a later line matching)
SPECS = {
    "Hardware": (B, r"# -+ hardware graph", ("block", r"    def target\(self\)")),
    "Tobqm": (P, r"    def to_bqm", None),
    "Qubo": (P, r"    def to_qubo", None),
    "Clique": (E, r"^class CliqueEmbedding", None),
    "Chainstats": (E, r"^def chain_stats", None),
    "Kwargs": (B, r"    def sample_kwargs", None),
    "Sample": (B, r"    def sample\(self, P", None),
    "Snapshot": (B, r"    def solver_snapshot", None),
    "Estaccess": (B, r"    def estimate_access_time", None),
    "Cbm": (B, r"^def _chain_break_method", None),
    "Stats": (B, r"^def sampleset_statistics", None),
    "Makesampler": (Q, r"    def make_sampler", None),
    "Seed": (S, r"# only samplers that declare a 'seed'", ("line", r"ss = self\._sampler\.sample\(bqm, \*\*kw\)", 2)),
    "Budget": (M, r"^class QPUBudget", ("block", r"^def _call_estimate")),
    "Anneal": (M, r"^def stage_anneal", None),
    "Spent": (M, r"^def qpu_spent", None),
    "Estcheck": (M, r"^def _estimate_qpu_time", None),
    "Collect": (M, r"for s, recs in ann\.items\(\):(?!.*reference)", ("before", r"^            for r in regimes:")),
    "Tts": (M, r"^def _time_per_read", ("block", r"^def _tts")),
    "Cbt": (M, r"^def chain_break_table", None),
    "Ground": (M, r"^def ground_states", None),
    "Validate": (M, r"^def validate", None),
}


def block_end(L, a):
    ind = len(L[a]) - len(L[a].lstrip())
    end = a
    for i in range(a + 1, len(L)):
        line = L[i]
        if line.strip() and len(line) - len(line.lstrip()) <= ind and not line.lstrip()[0] in ")]}":
            break
        if line.strip():
            end = i
    return end


def find(L, pat, after=0, k=1):
    hits = [i for i in range(after, len(L)) if re.search(pat, L[i])]
    return hits[k - 1]


lines = ["% generated by code_ranges.py -- do not edit"]
for name, (f, start, end) in SPECS.items():
    L = (SRC / f).read_text().split("\n")
    a = find(L, start)
    if end is None:
        b = block_end(L, a)
    elif end[0] == "block":
        b = block_end(L, find(L, end[1], a + 1))
    elif end[0] == "line":
        b = find(L, end[1], a + 1, end[2])
    else:
        b = find(L, end[1], a + 1) - 1
    lines.append(f"\\def\\r{name}A{{{a + 1}}}\\def\\r{name}B{{{b + 1}}}")
(HERE / "code_ranges.tex").write_text("\n".join(lines) + "\n")
print("\n".join(lines[1:]))
