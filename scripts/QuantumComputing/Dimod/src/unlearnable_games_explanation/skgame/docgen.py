def _fmt(v):
    v = _jsonable(v)
    s = str(v)
    return s if len(s) < 70 else s[:67] + "..."


def gen_objects() -> str:
    L = ["# 2. Mathematical objects", "",
         "Generated from `skgame/mathcat.py` by `python -m skgame.docgen` — edit that file, not this one.", "",
         "| object | symbol | space | paper | implementation |", "|---|---|---|---|---|"]
    for k, (sym, space, ref, impl) in OBJECTS.items():
        L.append(f"| `{k}` | {sym} | {space} | {ref} | `skgame.{impl}` |")
    L += ["", "Auxiliary objects of the code (not in the paper): `Recorder` streams (`RewardRecorder`, `WindowRecorder`,",
          "`SnapshotRecorder`, `TwoTimeRecorder`), `DMFTResult`, `PlannerProblem`, `SolveResult`, `BenchmarkResult`,",
          "`RunContext`, `Pipeline`."]
    return "\n".join(L) + "\n"


def gen_computations() -> str:
    L = ["# 3. Computations", "",
         "Generated by `python -m skgame.docgen`.", "",
         "## 3.1 Elementary computations (morphisms of the math category)", "",
         "| morphism | domain | codomain | formula / method |", "|---|---|---|---|"]
    for k, (dom, cod, d) in MORPHISMS.items():
        L.append(f"| `{k}` | {' ⊗ '.join(dom)} | {cod} | {d} |")
    L += ["", "## 3.2 Computations performed for the paper (output classes, in dependency order)", "",
          "Each row is one class; its folder is `output/<kind>/<Class>/` (result.npz + scalars.json + meta.json, or",
          "figure files). Parameters shown are the `quick` preset; `paper` presets reproduce the paper's sizes.", "",
          "| # | class | kind | paper | uses | quick parameters |", "|---|---|---|---|---|---|"]
    for n_, name in enumerate(topological_order(), 1):
        c = REGISTRY[name]
        if c.kind == "figure":
            continue
        uses = ", ".join(f"`{m}`" for m in OUTPUT_USES.get(name, []))
        params = "; ".join(f"{k}={_fmt(v)}" for k, v in c.presets.get("quick", {}).items())
        L.append(f"| {n_} | `{name}` | {c.kind} | {c.paper_ref} | {uses} | {params} |")
    L += ["", "## 3.3 Numerical methods", "",
          "* Direct simulation: batched over realisations, `np.matmul` on `(R,N,N)×(R,N)`.",
          "* Exact counting of fixed points / 2-cycles / ground states: Gray-code enumeration (numba), O(N 2^N).",
          "* Finite-T NMFE solutions: multistart damped iteration + Newton (`scipy.optimize.root`), duplicates merged.",
          "* L=2 complexity: saddle of Eq. (B40) under the 2-cycle ansatz, bivariate normal CDF via Owen's T,",
          "  numerical gradient + `hybr`/`lm` root finding, continuation in alpha.",
          "* DMFT: Monte-Carlo effective process (M paths, T steps), damped self-consistency, response via Novikov",
          "  (Cholesky of leading blocks).",
          "* Sompolinsky–Crisanti: quadrature of the energy integral (no shooting).",
          "* RS static DMFT: damped iteration + `hybr` in (q, k=β(1-ε)χ), outer-branch m(z).",
          "* Symbolic: SymPy (`theory/symbolic.py`), 13 identities, 2 of which correct typos in the paper."]
    return "\n".join(L) + "\n"


def gen_visualizations() -> str:
    figs = {n: REGISTRY[n] for n in REGISTRY if REGISTRY[n].kind == "figure"}
    L = ["# 4. Visualizations", "",
         "Generated by `python -m skgame.docgen`. Files: `output/figure/<Class>/*.png|pdf`.", "",
         "## 4.1 List, in the paper's order", "",
         "| paper | class | shows | supports claims | inputs |", "|---|---|---|---|---|"]
    for p in PAPER_ORDER:
        name = next(n for n in figs if n.startswith(p))
        what, claims = FIG_CLAIM[p]
        L.append(f"| {figs[name].paper_ref} | `{name}` | {what} | {claims} | "
                 f"{', '.join('`' + d.__name__ + '`' for d in figs[name].depends_on)} |")
    for name in figs:
        if not name[3:5].isdigit():
            L.append(f"| (new) | `{name}` | {figs[name].description} | P1 P2 | "
                     f"{', '.join('`' + d.__name__ + '`' for d in figs[name].depends_on)} |")
    L += ["", "## 4.2 Reading order (logical, not typographical)", "",
          "The paper's numbering mixes the non-technical overview (Sec. III) with the technical sections. The order",
          "in which the figures *build* the argument is:", "",
          "1. **Model and phases** — Fig. 1 (map of behaviours), Fig. 3 (what each phase looks like in C(τ)).",
          "2. **Welfare** — Fig. 2 (reward below R∞ everywhere; memory helps; noise helps a little; N^{-2/3}).",
          "3. **Who wins** — Figs. 4, 5, 6 (heterogeneous rewards, marginal stability, losers appear with ε),",
          "   Fig. 7 (winners are unpredictable).",
          "4. **A way out** — Fig. 8 (cooperation J0 > 1 removes radical complexity).",
          "5. **Why: landscape** — Fig. 9 (exponentially many fixed points for ε<1), Fig. 10 (cycles vs fixed points with memory).",
          "6. **Why: dynamics** — Fig. 11 (finite N vs DMFT at α=1), Fig. 12 (memory freezes cycles),",
          "   Fig. 13 (N→∞ first: chaos for ε≳0.5), Fig. 14 (exact ε=1 solution), Fig. 15 (α^{-1/2} cycles).",
          "7. **Noise** — Fig. 16 (where agents stay decided), Fig. 17 (static theory fails: RSB),",
          "   Fig. 18 (aging), Fig. 19 (noisy trajectories).",
          "8. **Planner** (this repository) — FigOptimizerScaling, FigSatisficingGap.", "",
          "## 4.3 Build order (topological order of the dependency category)", ""]
    order = [n for n in topological_order() if REGISTRY[n].kind == "figure"]
    L += [f"{k}. `{n}`" for k, n in enumerate(order, 1)]
    return "\n".join(L) + "\n"


def gen_mermaid() -> str:
    L = ["```mermaid", "flowchart LR"]
    for n in topological_order():
        for d in REGISTRY[n].depends_on:
            L.append(f"  {d.__name__} --> {n}")
    L.append("```")
    return "\n".join(L)


def main():
    (DOCS / "02_objects.md").write_text(gen_objects())
    (DOCS / "03_computations.md").write_text(gen_computations())
    (DOCS / "04_visualizations.md").write_text(gen_visualizations())
    p = DOCS / "05_dependencies.md"
    if p.exists():
        s = p.read_text()
        a, b = "<!-- BEGIN GENERATED -->", "<!-- END GENERATED -->"
        if a in s and b in s:
            s = s[: s.index(a) + len(a)] + "\n" + gen_mermaid() + "\n" + s[s.index(b):]
            p.write_text(s)
    print("docs regenerated")


if __name__ == "__main__":
    main()
